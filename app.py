@app.before_request
def csrf_protection() -> None:
    # Small dependency-free CSRF protection for browser form submissions.
    if "_csrf_token" not in session:
        session["_csrf_token"] = secrets.token_urlsafe(32)
    if request.method == "POST":
        expected = session.get("_csrf_token", "")
        supplied = request.form.get("_csrf_token", "")
        if not expected or not supplied or not hmac.compare_digest(expected, supplied):
            abort(400, description="Your form security token is missing or expired. Refresh the page and try again.")


@app.context_processor
def inject_template_helpers() -> dict[str, Any]:
    return {"csrf_token": lambda: session.get("_csrf_token", "")}


def _form_state() -> dict[str, Any]:
    return {
        "graph_title": request.form.get("graph_title", ""),
        "x_label": request.form.get("x_label", ""),
        "y_label": request.form.get("y_label", ""),
        "x_values": request.form.get("x_values", ""),
        "fixed_conditions": request.form.get("fixed_conditions", ""),
        "ann_target": request.form.get("ann_target", "Cfx"),
        "actual_values": request.form.get("actual_values", ""),
        "predicted_values": request.form.get("predicted_values", ""),
        "epochs": request.form.get("epochs", ""),
        "training_mse": request.form.get("training_mse", ""),
        "validation_mse": request.form.get("validation_mse", ""),
        "testing_mse": request.form.get("testing_mse", ""),
        "series": [
            {"label": label, "values": values}
            for label, values in zip(request.form.getlist("series_label[]"), request.form.getlist("series_values[]"))
        ],
    }


def _default_form_state(config: dict[str, Any]) -> dict[str, Any]:
    if config["kind"] in ("profile", "sensitivity"):
        return {
            "graph_title": config["title"],
            "x_label": config.get("x_axis", "Selected parameter value"),
            "y_label": config.get("y_axis", "Output value"),
            "x_values": "", "fixed_conditions": "",
            "series": [{"label": "Case 1", "values": ""}],
        }
    if config["kind"] in ("ann_error", "ann_regression"):
        return {"graph_title": config["title"], "ann_target": "Cfx", "actual_values": "", "predicted_values": ""}
    return {"graph_title": config["title"], "ann_target": "Cfx", "epochs": "", "training_mse": "",
            "validation_mse": "", "testing_mse": ""}


def _render_graph_page(config: dict[str, Any], *, form_state: dict[str, Any] | None = None,
                       result: dict[str, Any] | None = None, error: str | None = None,
                       status: int = 200):
    response = make_response(render_template(
        "graph_page.html", config=config,
        form_state=form_state if form_state is not None else _default_form_state(config),
        result=result, error=error,
    ), status)
    response.headers["Cache-Control"] = "no-store"
    return response


@app.get("/")
def index():
    return render_template("index.html", profile_pages=PROFILE_PAGES,
                           sensitivity_pages=SENSITIVITY_PAGES, ann_pages=ANN_PAGES)


@app.route("/graphs/<slug>", methods=["GET", "POST"])
def graph_page(slug: str):
    config = PROFILE_PAGES.get(slug) or SENSITIVITY_PAGES.get(slug)
    if config is None:
        abort(404)
    if request.method == "GET":
        return _render_graph_page(config)
    state = _form_state()
    try:
        if config["kind"] == "profile":
            result = create_profile_graph(config, request.form)
        else:
            result = create_sensitivity_graph(config, request.form)
        return _render_graph_page(config, form_state=state, result=result)
    except InputValidationError as exc:
        return _render_graph_page(config, form_state=state, error=str(exc), status=422)
    except Exception:
        app.logger.exception("Unexpected graph-generation error on /graphs/%s", slug)
        return _render_graph_page(
            config, form_state=state,
            error="The graph could not be generated because of an unexpected server error. Check the entered values and server log, then try again.",
            status=500,
        )


@app.route("/ann/<slug>", methods=["GET", "POST"])
def ann_page(slug: str):
    config = ANN_PAGES.get(slug)
    if config is None:
        abort(404)
    if request.method == "GET":
        return _render_graph_page(config)
    state = _form_state()
    try:
        if config["kind"] == "ann_error":
            result = create_error_histogram(request.form)
        elif config["kind"] == "ann_regression":
            result = create_regression_graph(request.form)
        else:
            result = create_performance_graph(request.form)
        return _render_graph_page(config, form_state=state, result=result)
    except InputValidationError as exc:
        return _render_graph_page(config, form_state=state, error=str(exc), status=422)
    except Exception:
        app.logger.exception("Unexpected ANN graph-generation error on /ann/%s", slug)
        return _render_graph_page(
            config, form_state=state,
            error="The graph could not be generated because of an unexpected server error. Check the entered values and server log, then try again.",
            status=500,
        )


@app.errorhandler(400)
def bad_request(error):
    return render_template("error.html", code=400, message=getattr(error, "description", "Bad request.")), 400


@app.errorhandler(404)
def not_found(error):
    return render_template("error.html", code=404, message="That graph page could not be found."), 404


@app.errorhandler(413)
def too_large(error):
    return render_template("error.html", code=413, message="The submitted form is too large. Reduce the number of values and try again."), 413


